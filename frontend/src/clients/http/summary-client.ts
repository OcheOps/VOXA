import type {
  GenerateSummaryRequest,
  MeetingSummaryResponse,
  ProcessingJobResponse,
  SummaryMarkdownContent,
  SummaryTemplateListResponse,
} from '@voxa/protocol';
import type {
  MeetingSummaryView,
  ServerSummaryClient,
  SummaryCancellationResult,
  SummaryCapabilities,
  SummaryClient,
  SummaryGenerationResult,
  SummaryRequest,
  SummaryRuntimeReadiness,
  SummaryState,
  SummaryStatus,
  SummaryTemplate,
} from '../contracts';
import { UnsupportedOperationError } from '../errors';
import { VoxaApiError, type HttpTransport } from './transport';

const STATUS: Record<MeetingSummaryResponse['state'], SummaryStatus> = {
  none: 'idle', queued: 'pending', generating: 'processing', ready: 'completed', failed: 'failed', cancelled: 'cancelled', unavailable: 'idle',
};

function markdownOf(content: unknown): { markdown: string; title: string | null } | null {
  const value = content as Partial<SummaryMarkdownContent> | null;
  if (!value || typeof value !== 'object' || typeof value.markdown !== 'string') return null;
  return { markdown: value.markdown, title: typeof value.title === 'string' && value.title ? value.title : null };
}

function toView(response: MeetingSummaryResponse): MeetingSummaryView {
  const summary = response.summary;
  const content = summary ? markdownOf(summary.content) : null;
  return {
    meetingId: response.meetingId,
    state: response.state,
    reason: response.reason,
    stale: response.stale,
    error: response.error,
    jobId: response.job?.id ?? null,
    progress: response.job?.progress ?? null,
    summary: summary && content ? {
      id: summary.id,
      markdown: content.markdown,
      title: content.title,
      provider: summary.provider ?? null,
      model: summary.model ?? null,
      templateId: summary.templateId ?? null,
      outputLanguage: summary.outputLanguage ?? null,
      transcriptId: summary.transcriptId ?? null,
      updatedAt: summary.updatedAt,
    } : null,
  };
}

const meetingPath = (meetingId: string) => `/api/v1/meetings/${encodeURIComponent(meetingId)}/summary`;

/**
 * Summaries generated by the Voxa server from stored transcripts. Provider,
 * model, endpoint and API keys are server configuration: nothing here sends
 * or receives credentials, and request fields such as `text`, `provider` or
 * `modelName` from the shared contract are ignored.
 */
export class HttpSummaryClient implements SummaryClient, ServerSummaryClient {
  readonly capabilities: SummaryCapabilities = {
    execution: 'remote',
    asynchronousJobs: true,
    polling: true,
    cancellation: true,
    templates: true,
    localRuntimePreflight: false,
    providers: ['openai', 'claude', 'groq', 'openrouter', 'ollama', 'custom-openai'],
  };

  constructor(private readonly transport: HttpTransport) {}

  // --- ServerSummaryClient ---

  async getMeetingSummary(meetingId: string, signal?: AbortSignal): Promise<MeetingSummaryView> {
    return toView(await this.transport.get<MeetingSummaryResponse>(meetingPath(meetingId), { signal }));
  }

  async generateSummary(meetingId: string, options: { templateId?: string; customPrompt?: string } = {}): Promise<void> {
    await this.startJob(meetingId, options);
  }

  async cancelSummary(meetingId: string): Promise<boolean> {
    try {
      await this.transport.post<ProcessingJobResponse>(`${meetingPath(meetingId)}/cancel`, {});
      return true;
    } catch (error) {
      if (error instanceof VoxaApiError && error.status === 409) return false;
      throw error;
    }
  }

  async listSummaryTemplates(): Promise<SummaryTemplate[]> {
    return (await this.transport.get<SummaryTemplateListResponse>('/api/v1/summary-templates')).items;
  }

  private async startJob(meetingId: string, options: { templateId?: string; customPrompt?: string }): Promise<ProcessingJobResponse> {
    const body: GenerateSummaryRequest = {};
    if (options.templateId) body.templateId = options.templateId;
    if (options.customPrompt) body.customPrompt = options.customPrompt;
    return this.transport.post<ProcessingJobResponse>(meetingPath(meetingId), body);
  }

  // --- SummaryClient (shared contract) ---

  async getState(meetingId: string): Promise<SummaryState> {
    const response = await this.transport.get<MeetingSummaryResponse>(meetingPath(meetingId));
    const content = response.summary ? markdownOf(response.summary.content) : null;
    return {
      status: STATUS[response.state],
      meetingName: content?.title ?? null,
      meetingId: response.meetingId,
      processId: response.job?.id ?? null,
      endedAt: response.job?.completedAt ?? null,
      data: response.summary?.content ?? null,
      error: response.error?.message ?? null,
    };
  }

  async generate(request: SummaryRequest): Promise<SummaryGenerationResult> {
    const response = await this.startJob(request.meetingId, { templateId: request.templateId || undefined, customPrompt: request.customPrompt || undefined });
    return { message: 'Summary generation queued', processId: response.job.id };
  }

  async cancel(meetingId: string): Promise<SummaryCancellationResult> {
    const cancelled = await this.cancelSummary(meetingId);
    return { cancelled, message: cancelled ? 'Summary generation cancelled' : 'No summary generation was running', meetingId };
  }

  async save(): Promise<void> {
    throw new UnsupportedOperationError('Editing server summaries');
  }

  async listTemplates(): Promise<SummaryTemplate[]> {
    return this.listSummaryTemplates();
  }

  /** There is no local runtime: the server checks provider readiness when a job runs. */
  async checkRuntime(): Promise<SummaryRuntimeReadiness> {
    return { ready: true };
  }
}
