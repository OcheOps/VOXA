import { afterAll, describe, expect, mock, test } from 'bun:test';
import { act, create, type ReactTestRenderer } from 'react-test-renderer';
import type { MeetingSummaryView, ServerSummaryClient, VoxaClient } from '../../src/clients/contracts';

const originalToast = { ...(await import('sonner')) };
afterAll(() => mock.module('sonner', () => originalToast));
mock.module('sonner', () => ({ toast: { error: () => {}, info: () => {}, success: () => {} } }));

const { VoxaClientProvider } = await import('../../src/clients');
const { SummaryPanel } = await import('../../src/web/SummaryPanel');

const result: NonNullable<MeetingSummaryView['summary']> = {
  id: 'sum_1', markdown: '**Key Decisions**\n\n- Ship on Friday\n\n<script>alert(1)</script>', title: 'Launch review', provider: 'openai', model: 'gpt-4o-mini',
  templateId: 'standard_meeting', outputLanguage: null, transcriptId: 'trn_1', updatedAt: '2026-10-20T10:00:00Z',
};
const view = (patch: Partial<MeetingSummaryView>): MeetingSummaryView => ({
  meetingId: 'mtg_1', state: 'none', reason: null, stale: false, error: null, jobId: null, progress: null, summary: null, ...patch,
});

function render(responses: MeetingSummaryView[]) {
  const calls: string[] = [];
  const summaries: ServerSummaryClient = {
    getMeetingSummary: async () => (responses.length > 1 ? responses.shift()! : responses[0]),
    generateSummary: async () => void calls.push('generate'),
    cancelSummary: async () => { calls.push('cancel'); return true; },
    listSummaryTemplates: async () => [],
  };
  let renderer!: ReactTestRenderer;
  act(() => {
    renderer = create(
      <VoxaClientProvider value={{ serverSummaries: summaries } as unknown as VoxaClient}>
        <SummaryPanel meetingId="mtg_1" />
      </VoxaClientProvider>,
    );
  });
  return { renderer: () => renderer, calls };
}

async function settle() {
  for (let i = 0; i < 5; i++) await act(async () => { await new Promise((r) => setTimeout(r, 0)); });
}

const text = (renderer: ReactTestRenderer) => JSON.stringify(renderer.toJSON());
const button = (renderer: ReactTestRenderer, label: string) =>
  renderer.root.findAll((node) => (node.type === 'button') && JSON.stringify(node.props.children).includes(label))[0];

describe('SummaryPanel', () => {
  test('renders a ready summary as Markdown without raw HTML, with provenance, and regenerates', async () => {
    const { renderer, calls } = render([view({ state: 'ready', summary: result }), view({ state: 'queued', jobId: 'job_2', summary: result })]);
    await settle();
    const output = text(renderer());
    expect(output).toContain('Launch review');
    expect(output).toContain('Ship on Friday');
    expect(output).toContain('"Generated by ","openai"');
    expect(output).toContain('gpt-4o-mini');
    expect(output).not.toContain('<script>');
    expect(renderer().root.findAll((node) => node.type === 'li').length).toBe(1);
    await act(async () => { button(renderer(), 'Regenerate').props.onClick(); });
    await settle();
    expect(calls).toEqual(['generate']);
    // While regenerating, the previous summary stays visible.
    expect(text(renderer())).toContain('Summary queued');
    expect(text(renderer())).toContain('Ship on Friday');
  });

  test('generating shows progress and cancels', async () => {
    const { renderer, calls } = render([view({ state: 'generating', jobId: 'job_2', progress: 0.5 }), view({ state: 'cancelled' })]);
    await settle();
    expect(text(renderer())).toContain('Generating summary');
    expect(text(renderer())).toContain('50');
    await act(async () => { button(renderer(), 'Cancel').props.onClick(); });
    await settle();
    expect(calls).toEqual(['cancel']);
    expect(text(renderer())).toContain('Summary generation was cancelled.');
  });

  test('failed regeneration keeps the previous summary and offers retry', async () => {
    const { renderer, calls } = render([view({ state: 'failed', error: { code: 'provider_auth_failed', message: 'The summary provider rejected the configured credentials.' }, summary: result })]);
    await settle();
    const output = text(renderer());
    expect(output).toContain('rejected the configured credentials');
    expect(output).toContain('Showing the previous summary.');
    expect(output).toContain('Ship on Friday');
    await act(async () => { button(renderer(), 'Retry').props.onClick(); });
    expect(calls).toEqual(['generate']);
  });

  test('stale summaries are labelled; unavailable and not-yet states explain why', async () => {
    const stale = render([view({ state: 'ready', stale: true, summary: result })]);
    await settle();
    expect(text(stale.renderer())).toContain('generated from an earlier transcript');

    for (const [patch, expected] of [
      [{ state: 'unavailable', reason: 'disabled' }, 'not available on this server'],
      [{ state: 'unavailable', reason: 'credential_missing' }, 'Add an API key'],
      [{ state: 'none', reason: 'no_transcript' }, 'once a transcript is ready'],
    ] as const) {
      const { renderer } = render([view(patch as Partial<MeetingSummaryView>)]);
      await settle();
      expect(text(renderer())).toContain(expected);
      expect(button(renderer(), 'Generate summary')).toBeUndefined();
      renderer().unmount();
    }
    const ready = render([view({ state: 'none' }), view({ state: 'queued', jobId: 'job_1' })]);
    await settle();
    await act(async () => { button(ready.renderer(), 'Generate summary').props.onClick(); });
    await settle();
    expect(ready.calls).toEqual(['generate']);
    expect(text(ready.renderer())).toContain('Summary queued');
  });
});
